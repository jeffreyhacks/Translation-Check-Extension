// Generates src/wordlists.js: everyday English vocabulary, and for each language with a word list, the English words that are ALSO words of that
// language ("impatient", "service", "menu" are French too). A word in the first list and not in the second is English-only for that language,
// which is evidence no statistical model gives for short strings: "Enthusiastic, decisive" on a French page. Run: npm run wordlists
// Sources (MIT / permissive): SCOWL via wordlist-english (frequency tiers 10-50), an-array-of-<language>-words.
import fs from 'fs';
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const J = (p) => JSON.parse(fs.readFileSync(require.resolve(p), 'utf8'));
const en = new Set();
for (const tier of [10, 20, 35, 40, 50]) for (const v of ['english', 'american', 'british']) {
  for (const w of J(`wordlist-english/${v}-words-${tier}.json`)) if (/^[a-z]{3,}$/.test(w)) en.add(w); // lower-case only: proper nouns are names, not vocabulary
}
const LISTS = { fr: 'an-array-of-french-words/index.json', es: 'an-array-of-spanish-words/index.json', de: ['an-array-of-german-words/words.json', 'all-the-german-words/woerter.json'],
  it: 'an-array-of-italian-words/words.json', pt: 'an-array-of-portuguese-words/words.json', nl: 'an-array-of-dutch-words/words.json' };
const shared = {}, owns = {};
for (const [lang, p] of Object.entries(LISTS)) {
  const own = new Set([p].flat().flatMap((f) => J(f)).map((w) => String(w).toLowerCase())); // an-array-of-german-words drops capitals ("ritik"), so German also uses all-the-german-words
  owns[lang] = own;
  shared[lang] = [...en].filter((w) => own.has(w)).sort().join(' ');
}
// Given names and surnames from faker's 70 locales (MIT), minus anything that is also an ordinary word in English or in one of the lists above
// (except German, whose big list contains names too): "Will", "Grace" or "Pierre" must still be judged as words, not waved through as names.
const faker = await import('@faker-js/faker');
const given = new Set(), family = new Set();
for (const [k, v] of Object.entries(faker)) {
  const p = k.startsWith('faker') && v?.rawDefinitions?.person;
  if (!p) continue;
  const add = (set, x) => { for (const n of [x || []].flat().flatMap((y) => (typeof y === 'object' && !Array.isArray(y) ? Object.values(y).flat() : y))) if (typeof n === 'string' && /^\p{Lu}\p{Ll}{2,}$/u.test(n)) set.add(n.toLowerCase()); };
  add(given, p.first_name); add(family, p.last_name);
}
const word = (w) => en.has(w) || ['fr', 'es', 'it', 'pt', 'nl'].some((l) => owns[l].has(w));
const NAMES = { given: [...given].filter((w) => !word(w)).sort().join(' '), family: [...family].filter((w) => !word(w) && !given.has(w)).sort().join(' ') };
const names = `// GENERATED by scripts/wordlists.mjs - do not edit. Given names and surnames from @faker-js/faker (MIT), ordinary words removed.
export const GIVEN_NAMES = ${JSON.stringify(NAMES.given)};
export const FAMILY_NAMES = ${JSON.stringify(NAMES.family)};
`;
fs.writeFileSync('src/namelists.js', names);
console.log('src/namelists.js', (names.length / 1024).toFixed(0) + ' KB,', NAMES.given.split(' ').length, 'given,', NAMES.family.split(' ').length, 'family');

const out = `// GENERATED by scripts/wordlists.mjs - do not edit. Word lists: SCOWL (Kevin Atkinson, permissive licence) and an-array-of-*-words (MIT).
export const EN_WORDS = ${JSON.stringify([...en].sort().join(' '))};
export const SHARED = ${JSON.stringify(shared)};
`;
fs.writeFileSync('src/wordlists.js', out);
console.log('src/wordlists.js', (out.length / 1024).toFixed(0) + ' KB,', en.size, 'English words,', Object.entries(shared).map(([l, s]) => `${l}:${s.split(' ').length}`).join(' '));
